function debugToggle( event )
  if event.phase == 'began' then
    print('debug')
    event.target:removeSelf()
  end
end

function startGame( event )
  if event.phase == 'began' then
    event.target:removeSelf()
    if composer.getSceneName("current") == "menu" then
      print('menu')
      timer.performWithDelay(50, playScene, 1)
    end
  end
end

function playScene()
  composer.removeScene('menu')
  composer.gotoScene( "play" )
end

function viewRecords( event )
  if event.phase == 'began' then
    print('records')
    event.target:removeSelf()
  end
end

